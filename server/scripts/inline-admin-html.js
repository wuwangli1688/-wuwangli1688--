#!/usr/bin/env node
/**
 * Pre-build script: inline admin dashboard HTML into a TypeScript module.
 * This ensures the admin dashboard content is bundled into dist/index.js,
 * because the production deployment does not reliably update server/public/admin/*.html.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const adminDir = path.resolve(__dirname, '../public/admin');
const outputDir = path.resolve(__dirname, '../src/generated');
const outputFile = path.join(outputDir, 'admin-html.ts');

const dashboard = fs.readFileSync(path.join(adminDir, 'dashboard.html'), 'utf-8');
const login = fs.readFileSync(path.join(adminDir, 'login.html'), 'utf-8');

const content = `// Auto-generated by scripts/inline-admin-html.js
// Do not edit this file manually.
export const dashboardHtml: string = ${JSON.stringify(dashboard)};
export const loginHtml: string = ${JSON.stringify(login)};
`;

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(outputFile, content, 'utf-8');

console.log(`✅ Inlined admin HTML to ${outputFile}`);
